// Подсказка размера по меркам (российская размерная сетка). Это ориентир, а не гарантия:
// у разных брендов лекала отличаются, поэтому в интерфейсе всегда пишем «ориентировочно».
const INTL = { 40: 'XXS', 42: 'XS', 44: 'S', 46: 'M', 48: 'L', 50: 'XL', 52: 'XXL', 54: '3XL', 56: '4XL', 58: '5XL', 60: '6XL' };

// Российский размер одежды ≈ половина обхвата груди (для низа — по бёдрам), округление до чётного.
const ruFrom = (cm) => Math.min(60, Math.max(40, 2 * Math.round(cm / 4)));

export function suggestSize(m, category) {
  if (!m) return null;
  if (category === 'Обувь') return m.shoe_eu ? { size: String(+m.shoe_eu), note: 'размер обуви (EU)' } : null;
  if (category === 'Аксессуары') return null;
  if (!m.chest_cm && !m.hips_cm) return null;
  // одежда: берём больший из «по груди» и «по бёдрам», чтобы вещь не жала
  const byChest = m.chest_cm ? ruFrom(m.chest_cm) : 0;
  const byHips = m.hips_cm ? ruFrom(m.hips_cm - (m.gender === 'male' ? 4 : 8)) : 0;
  const ru = Math.max(byChest, byHips);
  return { size: `${ru} (${INTL[ru] || '—'})`, note: 'российский размер одежды' };
}

